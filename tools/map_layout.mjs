#!/usr/bin/env node
// The build's positions, from the scroll map (map/README.md): map/world/<S>.json -> sections/<folder>/layout.json.
// The Blender builder and the page read structures, the road, trees and figures from layout.json by map ID, so
// nothing in a scene is placed by hand. Never edit layout.json; edit the map's strokes and regenerate.
//   node tools/map_layout.mjs <S>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (p) => path.join(ROOT, p);
const S = process.argv[2];
const SEC = JSON.parse(fs.readFileSync(r('map/sections.json'), 'utf8'))[S];
const AREA = SEC?.area || SEC?.x; // the part mapped and built so far
if (!SEC?.folder) { console.error(`section ${S} has no build folder in map/sections.json`); process.exit(1); }
const doc = JSON.parse(fs.readFileSync(r(`map/world/${S}.json`), 'utf8'));
const slug = (id) => id.split('.').slice(2).join('.');

// a tree card is drawn 8.5 m tall (web/src/gate.js placeTrees); scale it to the painted height, within reason (the
// painter draws far trees small, so small painted heights are floored at 0.7)
const CARD_M = 8.5;
const out = {
  about: `Generated by tools/map_layout.mjs from map/world/${S}.json; never edit. Metres in the section frame: X east (out of the city in S5), D north, H up. Entities keep their map IDs; figures and trees also carry their slug as id for people.json.`,
  section: S,
  frames: doc.frames,
  datum: doc.datum,
  route: null,
  figures: [],
  trees: [],
  entities: {},
};
for (const e of doc.entities) {
  if (e.kind === 'figure') {
    out.figures.push({ id: slug(e.id), map_id: e.id, X: e.pos[0], D: e.pos[1], H: e.H, pose: e.pose, facing_deg: e.facing_deg, support: e.support,
      station: e.station, side: e.side, est: e.est?.length ? e.est : undefined, group: e.group });
  } else if (e.kind === 'tree') {
    const h = e.height_m || CARD_M * 0.85;
    out.trees.push({ id: slug(e.id), map_id: e.id, X: e.pos[0], D: e.pos[1], H: e.H, support: e.support, height_m: e.height_m, crown_m: e.crown_m,
      scale: +Math.min(1.4, Math.max(0.7, h / (CARD_M * 0.85))).toFixed(2), what: e.what });
  } else if (e.kind !== 'group') {
    const k = {};
    for (const f of ['kind', 'name', 'pos', 'H', 'support', 'facing_deg', 'pose', 'pts', 'footprint', 'lines', 'lines_H', 'heights', 'bays', 'station', 'side', 'station_range', 'side_range', 'length_m', 'est'])
      if (e[f] != null && !(Array.isArray(e[f]) && !e[f].length)) k[f] = e[f];
    // a vehicle's `what` names its type, body and load (a boat's type, cabin, rig and cargo: the boat kit reads it)
    if (e.kind === 'vehicle' && e.what) k.what = e.what;
    out.entities[e.id] = k;
    if (e.route) out.route = { id: e.id, centre: e.lines.centre, edges: Object.fromEntries(Object.entries(e.lines).filter(([k]) => k !== 'centre')) };
  }
}
// each tree's painted card (trees/assign/<S>.json, the tree-card workshop: its form and variant, and whether it is
// mirrored), so the page shows the species the scroll paints, never one card for every tree
const assignPath = r(`trees/assign/${S}.json`);
if (fs.existsSync(assignPath)) {
  const assign = JSON.parse(fs.readFileSync(assignPath, 'utf8'));
  for (const t of out.trees) if (assign[t.map_id]) { t.card = assign[t.map_id].card; if (assign[t.map_id].flip) t.flip = true; }
}
// station of each route vertex (metres from the datum, + east), so paths can be given as station ranges
if (out.route && doc.datum) {
  const c = out.route.centre, acc = [0];
  for (let i = 1; i < c.length; i++) acc.push(acc[i - 1] + Math.hypot(c[i][0] - c[i - 1][0], c[i][1] - c[i - 1][1]));
  let best = { d: 1e9, s: 0 };
  for (let i = 0; i + 1 < c.length; i++) {
    const [ax, ay] = c[i], [bx, by] = c[i + 1], dx = bx - ax, dy = by - ay;
    const t = Math.max(0, Math.min(1, ((doc.datum.pos[0] - ax) * dx + (doc.datum.pos[1] - ay) * dy) / (dx * dx + dy * dy)));
    const d = Math.hypot(doc.datum.pos[0] - ax - t * dx, doc.datum.pos[1] - ay - t * dy);
    if (d < best.d) best = { d, s: acc[i] + t * Math.hypot(dx, dy) };
  }
  out.route.stations = acc.map((s) => +(s - best.s + (doc.datum.station || 0)).toFixed(2)); // datum.station: stations run on across sections
}
// the painted area: the section's scan rectangle (its two seams, the silk's bottom and top edges) on the ground (H 0),
// as [X, D] corners sw, se, ne, nw. Outside it the scroll paints nothing for this section: the build closes it with
// edges (air walls) and shows painting beyond them, never models (map/BUILDING.md)
const frameAt = (u) => doc.frames.find((f) => u >= f.covers[0] && u <= f.covers[1]) || doc.frames[0];
const dxAt = (f, u) => {
  const k = f.dx_knots;
  if (!k?.length) return f.d[0];
  if (u <= k[0][0]) return k[0][1];
  if (u >= k[k.length - 1][0]) return k[k.length - 1][1];
  for (let i = 0; i + 1 < k.length; i++) if (u <= k[i + 1][0]) return k[i][1] + ((u - k[i][0]) / (k[i + 1][0] - k[i][0])) * (k[i + 1][1] - k[i][1]);
};
const ground = (u, v) => { const f = frameAt(u); const D = (v - f.origin[1]) / f.d[1]; return [+((u - f.origin[0] - dxAt(f, u) * D) / f.x[0]).toFixed(2), +D.toFixed(2)]; };
const SILK_BOTTOM = 1790, SILK_TOP = 0;
out.painted_area = {
  about: `scan u ${AREA[0]}-${AREA[1]}, v ${SILK_TOP}-${SILK_BOTTOM} (the silk's edges) on the ground; corners sw, se, ne, nw`,
  corners: [ground(AREA[0], SILK_BOTTOM), ground(AREA[1], SILK_BOTTOM), ground(AREA[1], SILK_TOP), ground(AREA[0], SILK_TOP)],
};
// where the build departs from the map (sections/<folder>/build_choices.json): recorded moves, each with a reason
const choicesPath = r(`sections/${SEC.folder}/build_choices.json`);
if (fs.existsSync(choicesPath)) {
  const { moves = {} } = JSON.parse(fs.readFileSync(choicesPath, 'utf8'));
  out.moved = {};
  for (const [id, m] of Object.entries(moves)) {
    const t = [...out.figures, ...out.trees].find((x) => x.map_id === id) || (out.entities[id] && { ...out.entities[id], map_id: id, ref: out.entities[id] });
    if (!t) { console.warn(`build_choices: no ${id} in the map`); continue; }
    const o = t.ref ? t.ref.pos : null;
    const sh = (p) => { p[0] = +(p[0] + (m.dX || 0)).toFixed(2); p[1] = +(p[1] + (m.dD || 0)).toFixed(2); };
    if (o) {
      sh(o);
      // the whole entity moves: its points (an animal's hooves, a cart's front and wheels), footprint and bays, so
      // whatever is built from them (a yoke on the hooves, a wall on the footprint) follows the recorded move
      for (const p of Object.values(t.ref.pts || {})) if (Array.isArray(p) && typeof p[0] === 'number') sh(p);
      for (const p of t.ref.footprint || []) sh(p);
      for (const p of t.ref.bays || []) sh(p);
    } else { t.X = +(t.X + (m.dX || 0)).toFixed(2); t.D = +(t.D + (m.dD || 0)).toFixed(2); }
    out.moved[id] = m;
  }
}
const file = r(`sections/${SEC.folder}/layout.json`);
fs.writeFileSync(file, JSON.stringify(out, null, 1).replace(/\[\n\s+(-?[\d.]+),\n\s+(-?[\d.]+)(?:,\n\s+(-?[\d.]+))?\n\s+\]/g, (m, a, b, c) => `[${a}, ${b}${c != null ? ', ' + c : ''}]`) + '\n');
console.log(`${path.relative(ROOT, file)}: ${out.figures.length} figures, ${out.trees.length} trees, ${Object.keys(out.entities).length} other entities, route ${out.route?.id || 'none'}, ${Object.keys(out.moved || {}).length} recorded moves`);
