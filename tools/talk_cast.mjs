#!/usr/bin/env node
// The cast sheet a talk writer works from (gen/life/progress.md): for one section, every painted group with its
// members, and every figure on its own, each with what the map says it does (map/world/<S>.json), where it stands
// (layout.json X, D), and what it plays (people.json: character, do-cycle clips, or a walker's clip). Lines must fit
// those clips (a sleeper only thinks; a porter on the move doesn't haggle).
//   node tools/talk_cast.mjs S4            -> gen/life/cast/S4.md
//   node tools/talk_cast.mjs all
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const secs = read('map/sections.json');
const want = process.argv[2] || 'all';
const keys = want === 'all' ? Object.keys(secs).filter((k) => k !== 'about' && secs[k].folder) : [want];

for (const S of keys) {
  const folder = secs[S]?.folder;
  if (!folder) { console.error(`${S}: no folder`); continue; }
  const W = read(`map/world/${S}.json`), L = read(`sections/${folder}/layout.json`), P = read(`sections/${folder}/people.json`);
  const ents = Array.isArray(W.entities) ? W.entities : Object.entries(W.entities).map(([id, e]) => ({ id, ...e }));
  const byId = new Map(ents.map((e) => [e.id, e]));
  const figs = new Map((L.figures || []).map((f) => [f.id, f]));
  const walkers = new Map((P.walkers || []).map((w) => [w.id, w]));
  const slug = (id) => id.split('.').slice(2).join('.');
  const plays = (s) => {
    const sp = P.figures?.[s], wk = walkers.get(s);
    if (sp) return `${sp.character}${sp.carried_by ? ` (carried by ${sp.carried_by})` : ''}${sp.ride ? ` (rides ${sp.ride})` : ''}: ${(sp.do || (sp.ride ? [['ride', 8]] : [['idle', 6]])).map(([c]) => c).join(', ')}`;
    if (wk) return `${wk.character}: walker, ${wk.clip}${wk.pause ? `, pauses ${wk.pause[0]}` : ''}`;
    return null;
  };
  const at = (s) => { const f = figs.get(s); return f ? `X ${f.X.toFixed(1)}, D ${f.D.toFixed(1)}${f.H ? `, H ${f.H}` : ''}` : 'not in layout'; };
  const inGroup = new Set();
  const out = [`# ${S} (${folder}): the cast for talk`, '',
    `Generated by \`node tools/talk_cast.mjs ${S}\` from map/world/${S}.json, sections/${folder}/layout.json and people.json. Do not edit.`,
    'Each figure: `slug` (what to put in a role\'s "fig"), what the map says, where (X east, D north, metres), and what it plays',
    '(character: the clips of its do-cycle). "not placed" = no people.json entry: it cannot speak.', '', '## Groups', ''];
  for (const g of ents.filter((e) => e.id.includes('.grp.'))) {
    const mem = (g.members || []).filter((m) => m.includes('.fig.'));
    out.push(`### ${g.name} \`${g.id}\``, '', g.what || '', '');
    for (const m of mem) {
      const s = slug(m), e = byId.get(m);
      inGroup.add(s);
      out.push(`- \`${s}\`: ${e?.name || '?'}. ${at(s)}. Plays ${plays(s) || '**not placed**'}.`);
    }
    const other = (g.members || []).filter((m) => !m.includes('.fig.')).map((m) => `${byId.get(m)?.name || m} \`${m}\``);
    if (other.length) out.push(`- with: ${other.join('; ')}`);
    out.push('');
  }
  out.push('## Figures on their own', '');
  for (const e of ents.filter((x) => x.id.includes('.fig.') && !inGroup.has(slug(x.id)))) {
    const s = slug(e.id);
    out.push(`- \`${s}\`: ${e.name}. ${(e.what || '').replace(/\s+/g, ' ')} ${at(s)}. Plays ${plays(s) || '**not placed**'}.`);
  }
  fs.mkdirSync(path.join(ROOT, 'gen/life/cast'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, `gen/life/cast/${S}.md`), out.join('\n') + '\n');
  console.log(`${S}: ${ents.filter((e) => e.id.includes('.grp.')).length} groups, ${ents.filter((x) => x.id.includes('.fig.')).length} figures -> gen/life/cast/${S}.md`);
}
