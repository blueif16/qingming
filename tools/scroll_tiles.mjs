#!/usr/bin/env node
// The original painting for the web: the scan (reference/scroll/qingming_commons_38414x1800.jpg, the Palace
// Museum's 清明上河图 via Wikimedia Commons, public domain) as a webp tile pyramid that the scroll HUD
// (web/src/scroll_hud.js) loads tile by tile while it is open, plus one small whole-scroll strip.
//   web/public/assets/scroll/tiles.json         the manifest: scan size, tile size, levels, strip, credit
//   web/public/assets/scroll/<level>/<col>_<row>.webp   level 0 = full resolution, 1 = 1/2, 2 = 1/4, 3 = 1/8
//   web/public/assets/scroll/strip.webp         the whole scroll, STRIP_H px tall (the HUD's bottom strip and the
//                                               view's placeholder while tiles load)
// The painting is shown as it is: no tone matching (its aged colours are right here, it is the original).
//   node tools/scroll_tiles.mjs [--quality 70] [--levels 4] [--tile 512]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharp = createRequire(path.join(ROOT, 'tools/package.json'))('sharp');
const SCAN = path.join(ROOT, 'reference/scroll/qingming_commons_38414x1800.jpg');
const OUT = path.join(ROOT, 'web/public/assets/scroll');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(`--${k}`); return i >= 0 ? +args[i + 1] : d; };
const QUALITY = opt('quality', 70), LEVELS = opt('levels', 4), TILE = opt('tile', 512), STRIP_H = opt('strip', 128);

sharp.concurrency(4);
const { data, info } = await sharp(SCAN, { limitInputPixels: false }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width, H = info.height;
// files are overwritten in place and only stale ones deleted afterwards: removing and re-creating these folders under
// a running Vite dev server loses its watch on them, and it then serves index.html for every new tile
// (assets/scroll/sections.json is tools/scroll_index.mjs's)
fs.mkdirSync(OUT, { recursive: true });
const written = new Set();
const manifest = {
  about: 'Generated by tools/scroll_tiles.mjs from reference/scroll/qingming_commons_38414x1800.jpg; never edit. Tiles: <level>/<col>_<row>.webp, level L is the scan at 1/2^L; scan pixel (u, v) is at (u, v) / 2^L in its level.',
  credit: 'Palace Museum, via Wikimedia Commons',
  source: 'the Wikimedia Commons scan of the Palace Museum scroll, 38414 x 1800 (public domain)',
  width: W, height: H, tile: TILE, format: 'webp', levels: [], strip: null,
};
let bytes = 0, files = 0;
const write = async (img, file) => { await img.webp({ quality: QUALITY, effort: 5 }).toFile(file); bytes += fs.statSync(file).size; files++; written.add(file); };
for (let L = 0; L < LEVELS; L++) {
  const s = 2 ** L, w = Math.round(W / s), h = Math.round(H / s);
  const lvl = L === 0 ? { data, info } : await sharp(data, { raw: { width: W, height: H, channels: 3 }, limitInputPixels: false })
    .resize(w, h, { kernel: 'lanczos3' }).raw().toBuffer({ resolveWithObject: true });
  const cols = Math.ceil(w / TILE), rows = Math.ceil(h / TILE);
  fs.mkdirSync(path.join(OUT, String(L)), { recursive: true });
  const jobs = [];
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) jobs.push([c, r]);
  for (let i = 0; i < jobs.length; i += 8) {
    await Promise.all(jobs.slice(i, i + 8).map(([c, r]) => {
      const left = c * TILE, top = r * TILE, width = Math.min(TILE, w - left), height = Math.min(TILE, h - top);
      return write(sharp(lvl.data, { raw: { width: w, height: h, channels: 3 }, limitInputPixels: false }).extract({ left, top, width, height }),
        path.join(OUT, String(L), `${c}_${r}.webp`));
    }));
  }
  manifest.levels.push({ level: L, scale: s, width: w, height: h, cols, rows });
  console.log(`level ${L} (1/${s}): ${w} x ${h}, ${cols} x ${rows} tiles`);
}
const sw = Math.round((W * STRIP_H) / H);
await write(sharp(data, { raw: { width: W, height: H, channels: 3 }, limitInputPixels: false }).resize(sw, STRIP_H, { kernel: 'lanczos3' }), path.join(OUT, 'strip.webp'));
manifest.strip = { file: 'strip.webp', width: sw, height: STRIP_H };
fs.writeFileSync(path.join(OUT, 'tiles.json'), JSON.stringify(manifest, null, 1) + '\n');
for (const d of fs.readdirSync(OUT)) { // stale tiles (another tile size or fewer levels before)
  const dir = path.join(OUT, d);
  if (!/^\d+$/.test(d) || !fs.statSync(dir).isDirectory()) continue;
  for (const f of fs.readdirSync(dir)) if (!written.has(path.join(dir, f))) fs.rmSync(path.join(dir, f));
}
const perLevel = manifest.levels.map((l) => {
  const dir = path.join(OUT, String(l.level));
  return `${l.level}: ${(fs.readdirSync(dir).reduce((s, f) => s + fs.statSync(path.join(dir, f)).size, 0) / 1e6).toFixed(2)} MB`;
});
console.log(`${files} files, ${(bytes / 1e6).toFixed(2)} MB (${perLevel.join(', ')}; strip ${(fs.statSync(path.join(OUT, 'strip.webp')).size / 1e3).toFixed(0)} kB) -> ${path.relative(ROOT, OUT)}`);
